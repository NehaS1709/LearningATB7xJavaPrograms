package ex_02092024;

public class Lab015 {
    public static void main(String[] args) {

        // Structure of variable is as follows:
        // data_type variable_name = variable_value(literal)


        //Data types:
        //there are 2 types
        //A) Primitive data types
          //1. boolean-True or false
            // eg.
        boolean married = true;
        boolean are_you_a_dog = false;
        System.out.println(married);
        System.out.println(are_you_a_dog);



          //2. Numerical
                //a.Integral
                    //1. byte: eg-
        byte b = 127;
        System.out.println(b);
                    //2. short: eg-
        short s = 100;
        System.out.println(s);
                    //3. int: eg-
        int age = 130;
        System.out.println(age);
                    //4. long: while using long use L at the end of
                        // value without space eg-
        long phone_number = 9876543210L;
        System.out.println(phone_number);
                    //5. char-> can only stores characters -> A,a,B,b,etc
                        // use single inverted commas '' for value for char only
        char grade = 'A';
        System.out.println(grade);

                //b.floating point
                    //1. float: while using long use F or f at the end of
                        // value without space eg:
        float pi = 3.14F;
        System.out.println(pi);
                    //2. double:eg-
        double d = 118.6548;
        System.out.println(d);


        //B) Non-Primitive data types




    }
}
